// Generates the per-language option types, tokens and the options reference from spec/.
// Run: node spec/generate.mjs   (CI runs it with --check and fails if anything is stale)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(readFileSync(join(root, 'spec/options.schema.json'), 'utf8'));
const tokens = JSON.parse(readFileSync(join(root, 'spec/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const HEADER = 'GENERATED by spec/generate.mjs from spec/. Do not edit.';
const props = Object.entries(schema.properties);
const types = schema.properties.type.enum;
let stale = 0;

function emit(rel, text) {
  const file = join(root, rel);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error(`stale: ${rel}`); stale++; }
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

// ── TypeScript ──
const tsType = p => p['x-ts'] || (p.enum ? p.enum.map(v => `'${v}'`).join(' | ') : { string: 'string', number: 'number', integer: 'number', boolean: 'boolean' }[p.type] || 'unknown');
emit('js/src/generated/options.ts', `// ${HEADER}
/* eslint-disable */
import type { Data, Channel, FormatName, AxisOptions, Annotation, ChartPoint, ThemeTokens } from '../core/model-types';

export const CHART_TYPES = ${JSON.stringify(types)} as const;
export type ChartType = typeof CHART_TYPES[number];

export interface SeriesOptions {
${Object.entries(schema.$defs.SeriesOptions.properties).map(([k, p]) => `  ${p.description ? `/** ${p.description} */\n  ` : ''}${k}?: ${tsType(p)};`).join('\n')}
}

/** ${schema.description} */
export interface ChartOptions {
${props.map(([k, p]) => `  /** ${p.description} */\n  ${k}${k === 'type' ? '' : '?'}: ${k === 'type' ? 'ChartType' : tsType(p)};`).join('\n')}
}

export const OPTION_KEYS = ${JSON.stringify(props.map(([k]) => k))} as const;
`);

emit('js/src/generated/tokens.ts', `// ${HEADER}
export const TOKENS = ${JSON.stringify(tokens, null, 2)} as const;
`);

// ── Dart ──
const camel = s => s.replace(/[-_](\w)/g, (_, c) => c.toUpperCase());
const dartType = p => p['x-dart'] || (p.enum ? 'String?' : { string: 'String?', number: 'double?', integer: 'int?', boolean: 'bool?' }[p.type] || 'Object?');
const dartProps = props.filter(([k]) => k !== 'type' && k !== 'data');
emit('flutter/lib/src/generated/options.g.dart', `// ${HEADER}
// ignore_for_file: public_member_api_docs

/// Every chart type, in the same order as the JS \`CHART_TYPES\`.
enum ChartType { ${types.map(t => camel(t)).join(', ')} }

const Map<ChartType, String> chartTypeNames = {
${types.map(t => `  ChartType.${camel(t)}: '${t}',`).join('\n')}
};

ChartType chartTypeFromName(String name) =>
    chartTypeNames.entries.firstWhere((e) => e.value == name, orElse: () => throw ArgumentError('craggy_charts: unknown chart type "$name"')).key;

/// ${schema.description}
class ChartOptions {
  const ChartOptions({
    required this.type,
    this.data,
${dartProps.map(([k]) => `    this.${k},`).join('\n')}
  });

  /// ${schema.properties.type.description}
  final ChartType type;

  /// ${schema.properties.data.description}
  final Object? data;
${dartProps.map(([k, p]) => `\n  /// ${p.description}\n  final ${dartType(p)} ${k};`).join('\n')}

  /// The options as the same JSON object the JS API takes.
  Map<String, Object?> toJson() => {
        'type': chartTypeNames[type],
        if (data != null) 'data': data,
${dartProps.map(([k]) => `        if (${k} != null) '${k}': ${k},`).join('\n')}
      };

  /// Build from the JS options object.
  factory ChartOptions.fromJson(Map<String, Object?> j) => ChartOptions(
        type: chartTypeFromName(j['type']! as String),
        data: j['data'],
${dartProps.map(([k, p]) => {
  const t = dartType(p);
  const cast = t === 'double?' ? `(j['${k}'] as num?)?.toDouble()` : t === 'int?' ? `(j['${k}'] as num?)?.toInt()`
    : t.startsWith('Map<String, Map') ? `(j['${k}'] as Map?)?.map((k, v) => MapEntry(k as String, Map<String, Object?>.from(v as Map)))`
    : t.startsWith('Map') ? `j['${k}'] == null ? null : Map<String, Object?>.from(j['${k}']! as Map)`
    : t.startsWith('List') ? `(j['${k}'] as List?)?.map((e) => Map<String, Object?>.from(e as Map)).toList()`
    : t === 'Object?' ? `j['${k}']` : `j['${k}'] as ${t}`;
  return `        ${k}: ${cast},`;
}).join('\n')}
      );
}
`);

const dartVal = v => typeof v === 'string' ? `'${v.replace(/'/g, "\\'")}'` : Array.isArray(v) ? `[${v.map(dartVal).join(', ')}]`
  : v && typeof v === 'object' ? `{${Object.entries(v).map(([k, x]) => `'${k}': ${dartVal(x)}`).join(', ')}}` : String(v);
emit('flutter/lib/src/generated/tokens.g.dart', `// ${HEADER}
// ignore_for_file: public_member_api_docs

const Map<String, Object> tokens = ${dartVal(tokens)};
`);

// ── Python ──
emit('python/craggy_charts/_generated.py', `# ${HEADER}
CHART_TYPES = ${JSON.stringify(types)}
OPTION_KEYS = ${JSON.stringify(props.map(([k]) => k))}
`);

// ── Reference docs ──
emit('docs/options.md', `<!-- ${HEADER} -->
# Options reference

${schema.description}

| Option | Type | Description |
|---|---|---|
${props.map(([k, p]) => `| \`${k}\` | \`${tsType(p).replace(/\|/g, '\\|')}\` | ${p.description} |`).join('\n')}

## Per-series options (\`series: { name: {...} }\`)

| Option | Type | Description |
|---|---|---|
${Object.entries(schema.$defs.SeriesOptions.properties).map(([k, p]) => `| \`${k}\` | \`${tsType(p).replace(/\|/g, '\\|')}\` | ${p.description || ''} |`).join('\n')}

## Chart types

${types.map(t => `\`${t}\``).join(', ')}
`);

if (check && stale) { console.error(`${stale} generated file(s) are stale: run node spec/generate.mjs`); process.exit(1); }
console.log(check ? 'generated files are up to date' : 'generated');
